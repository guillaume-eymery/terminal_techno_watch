# ---------------------------------------------------------------- output
def now_utc() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc)


def write(payload: dict) -> None:
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    OUT_JS.write_text("// Generated by scripts/vessels.py - do not edit by hand.\n"
                      "window.PORT_RADAR_VESSELS = " + json.dumps(payload, ensure_ascii=False) + ";\n",
                      encoding="utf-8")
    print(f"{len(payload['vessels'])} vessel(s) -> {OUT_JSON.relative_to(ROOT)}, {OUT_JS.relative_to(ROOT)}")


# ---------------------------------------------------------------- minimal WebSocket client
class WebSocket:
    """Minimal WebSocket client (RFC 6455): TLS, optional HTTP CONNECT proxy, text frames."""

    def __init__(self, url: str, timeout: float = 30):
        u = urlsplit(url)
        host, port = u.hostname, u.port or 443
        proxy = os.environ.get("HTTPS_PROXY") or os.environ.get("https_proxy")
        if proxy:
            p = urlsplit(proxy if "://" in proxy else f"http://{proxy}")
            raw = socket.create_connection((p.hostname, p.port or 8080), timeout=timeout)
            raw.sendall(f"CONNECT {host}:{port} HTTP/1.1\r\nHost: {host}:{port}\r\n\r\n".encode())
            head = self._read_head(raw)
            if b" 200" not in head.split(b"\r\n")[0]:
                raise ConnectionError(f"Proxy refused the tunnel: {head.splitlines()[0].decode(errors='replace')}")
        else:
            raw = socket.create_connection((host, port), timeout=timeout)
        self.sock = ssl.create_default_context().wrap_socket(raw, server_hostname=host)
        key = base64.b64encode(os.urandom(16)).decode()
        self.sock.sendall((f"GET {u.path or '/'} HTTP/1.1\r\nHost: {host}\r\nUpgrade: websocket\r\n"
                           f"Connection: Upgrade\r\nSec-WebSocket-Key: {key}\r\nSec-WebSocket-Version: 13\r\n\r\n").encode())
        head, self.buf = self._read_head(self.sock, keep_rest=True)
        if b" 101" not in head.split(b"\r\n")[0]:
            raise ConnectionError(f"WebSocket handshake refused: {head.splitlines()[0].decode(errors='replace')}")

    @staticmethod
    def _read_head(sock, keep_rest=False):
        data = b""
        while b"\r\n\r\n" not in data:
            chunk = sock.recv(4096)
            if not chunk:
                raise ConnectionError("Connection closed during handshake")
            data += chunk
        head, rest = data.split(b"\r\n\r\n", 1)
        return (head, rest) if keep_rest else head

    def _recv_exact(self, n: int) -> bytes:
        while len(self.buf) < n:
            chunk = self.sock.recv(65536)
            if not chunk:
                raise ConnectionError("Connection closed by server")
            self.buf += chunk
        out, self.buf = self.buf[:n], self.buf[n:]
        return out

    def send(self, payload: bytes, opcode: int = 1) -> None:
        header = bytes([0x80 | opcode])
        n = len(payload)
        if n < 126:
            header += bytes([0x80 | n])
        elif n < 65536:
            header += bytes([0x80 | 126]) + struct.pack(">H", n)
        else:
            header += bytes([0x80 | 127]) + struct.pack(">Q", n)
        mask = os.urandom(4)
        self.sock.sendall(header + mask + bytes(b ^ mask[i % 4] for i, b in enumerate(payload)))

    def recv(self) -> bytes | None:
        """Return the next complete message (text or binary), None on close."""
        message = b""
        while True:
            b1, b2 = self._recv_exact(2)
            fin, opcode, n = b1 & 0x80, b1 & 0x0F, b2 & 0x7F
            if n == 126:
                n = struct.unpack(">H", self._recv_exact(2))[0]
            elif n == 127:
                n = struct.unpack(">Q", self._recv_exact(8))[0]
            mask = self._recv_exact(4) if b2 & 0x80 else None
            data = self._recv_exact(n)
            if mask:
                data = bytes(b ^ mask[i % 4] for i, b in enumerate(data))
            if opcode == 8:
                return None
            if opcode == 9:
                self.send(data, opcode=10)
                continue
            if opcode == 10:
                continue
            message += data
            if fin:
                return message

    def close(self) -> None:
        try:
            self.send(b"", opcode=8)
            self.sock.close()
        except OSError:
            pass


# ---------------------------------------------------------------- aisstream.io
def clean_name(s) -> str:
    return re.sub(r"\s+", " ", str(s or "").replace("@", " ")).strip()


def fmt_eta(eta) -> str | None:
    if not isinstance(eta, dict) or not eta.get("Month") or not eta.get("Day"):
        return None
    return f"{eta['Day']:02d}/{eta['Month']:02d} {eta.get('Hour', 0):02d}:{eta.get('Minute', 0):02d} UTC"


def load_previous() -> dict[str, dict]:
    try:
        data = json.loads(OUT_JSON.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if data.get("demo"):
        return {}
    return {str(v["mmsi"]): v for v in data.get("vessels", []) if v.get("mmsi") and v.get("timestamp")}


def cmd_ais(minutes: float, pattern: str) -> dict:
    key = os.environ.get("AISSTREAM_API_KEY")
    if not key:
        sys.exit("AISSTREAM_API_KEY is not set (setx AISSTREAM_API_KEY <key>, then reopen the terminal).")
    name_re = re.compile(pattern, re.I)
    fleet = load_previous()
    seen: set[str] = set()
    statics: dict[str, dict] = {}
    stats = {"messages": 0, "reconnects": 0}
    deadline = time.monotonic() + minutes * 60
    subscribe = json.dumps({
        "APIKey": key,
        "BoundingBoxes": [[[-90, -180], [90, 180]]],
        "FilterMessageTypes": ["PositionReport", "ShipStaticData"],
    }).encode()

    print(f"Listening to aisstream.io for {minutes:g} min (pattern: {pattern})...")
    last_print = time.monotonic()
    while time.monotonic() < deadline:
        try:
            ws = WebSocket(AISSTREAM_URL)
            ws.send(subscribe)
            while time.monotonic() < deadline:
                raw = ws.recv()
                if raw is None:
                    raise ConnectionError("closed by server")
                stats["messages"] += 1
                msg = json.loads(raw)
                if "error" in msg:
                    sys.exit(f"aisstream.io: {msg['error']}")
                meta = msg.get("MetaData", {})
                name = clean_name(meta.get("ShipName"))
                if not name_re.search(name):
                    continue
                mmsi = str(meta.get("MMSI"))
                body = msg.get("Message", {})
                if msg.get("MessageType") == "ShipStaticData":
                    s = body.get("ShipStaticData", {})
                    statics[mmsi] = {"imo": s.get("ImoNumber") or None,
                                     "destination": clean_name(s.get("Destination")) or None,
                                     "eta": fmt_eta(s.get("Eta"))}
                    continue
                p = body.get("PositionReport", {})
                lat, lon = p.get("Latitude", meta.get("latitude")), p.get("Longitude", meta.get("longitude"))
                if lat is None or lon is None or abs(lat) > 90 or abs(lon) > 180:
                    continue
                heading = p.get("TrueHeading")
                hdg = heading if heading is not None and heading < 360 else p.get("Cog")
                v = fleet.get(mmsi, {})
                v.update({"name": name.title().replace("Cma Cgm", "CMA CGM"), "mmsi": mmsi,
                          "lat": round(lat, 5), "lon": round(lon, 5),
                          "heading": round(hdg) if hdg is not None and hdg < 360 else None,
                          "speed_knots": p.get("Sog") if p.get("Sog") is not None and p["Sog"] < 102.3 else None,
                          "status": NAV_STATUS.get(p.get("NavigationalStatus")),
                          "timestamp": now_utc().isoformat(timespec="seconds")})
                v.setdefault("imo", None); v.setdefault("destination", None); v.setdefault("eta", None)
                fleet[mmsi] = v
                seen.add(mmsi)
                if time.monotonic() - last_print > 30:
                    left = max(0, deadline - time.monotonic())
                    print(f"  {stats['messages']} messages read · {len(seen)} CMA CGM vessel(s) heard · {left / 60:.1f} min left")
                    last_print = time.monotonic()
            ws.close()
        except (OSError, ConnectionError, ValueError) as e:
            if isinstance(e, ssl.SSLCertVerificationError):
                sys.exit("TLS certificate rejected (corporate TLS inspection?). Try off VPN.")
            stats["reconnects"] += 1
            if stats["reconnects"] > 5:
                sys.exit(f"Cannot connect to aisstream.io: {e}")
            print(f"  connection interrupted ({e}), retrying...")
            time.sleep(3)

    for mmsi, s in statics.items():
        if mmsi in fleet:
            fleet[mmsi].update({k: v for k, v in s.items() if v})
    cutoff = now_utc() - dt.timedelta(hours=MAX_AGE_HOURS)
    vessels = [v for v in fleet.values()
               if dt.datetime.fromisoformat(v.get("timestamp", "1970-01-01T00:00:00+00:00")) >= cutoff]
    vessels.sort(key=lambda v: v["name"])
    print(f"{stats['messages']} AIS messages read · {len(seen)} vessel(s) heard this run · "
          f"{len(vessels)} displayed (positions less than {MAX_AGE_HOURS} h old)")
    return {"updated_at": now_utc().isoformat(timespec="seconds"),
            "source": "Terrestrial AIS - aisstream.io", "demo": False, "vessels": vessels}


# ---------------------------------------------------------------- demo / generic HTTP API
def cmd_demo() -> dict:
    return {
        "updated_at": now_utc().isoformat(timespec="seconds"), "source": "Simulated positions (demo)", "demo": True,
        "vessels": [{"name": n, "imo": None, "mmsi": None, "lat": la, "lon": lo, "heading": h,
                     "speed_knots": v, "destination": d, "eta": None, "status": "under way (engine)"}
                    for n, la, lo, h, v, d in DEMO],
    }


def normalize(raw) -> list[dict]:
    """ADAPT to the format of an HTTP API. Generic version: list of objects
    (or {"vessels": [...]} / {"data": [...]}) with common AIS field names."""
    items = raw if isinstance(raw, list) else raw.get("vessels") or raw.get("data") or []

    def pick(d, *keys):
        for k in keys:
            if d.get(k) not in (None, ""):
                return d[k]
        return None

    out = []
    for v in items:
        lat, lon = pick(v, "lat", "latitude", "LAT"), pick(v, "lon", "lng", "longitude", "LON")
        if lat is None or lon is None:
            continue
        out.append({
            "name": pick(v, "name", "vesselName", "SHIPNAME") or "Vessel",
            "imo": pick(v, "imo", "IMO"), "mmsi": pick(v, "mmsi", "MMSI"),
            "lat": float(lat), "lon": float(lon),
            "heading": pick(v, "heading", "course", "cog", "HEADING", "COURSE"),
            "speed_knots": pick(v, "speed_knots", "speed", "sog", "SPEED"),
            "destination": pick(v, "destination", "DESTINATION"),
            "eta": pick(v, "eta", "ETA"),
            "status": pick(v, "status", "navStatus"),
            "timestamp": pick(v, "timestamp", "time", "TIMESTAMP"),
        })
    return out


def cmd_fetch() -> dict:
    url = os.environ.get("VESSELS_API_URL")
    if not url:
        sys.exit("VESSELS_API_URL is not set.")
    req = urllib.request.Request(url, headers={"Accept": "application/json"})
    if key := os.environ.get("VESSELS_API_KEY"):
        req.add_header(os.environ.get("VESSELS_API_AUTH", "Authorization"), key)
    with urllib.request.urlopen(req, timeout=30) as r:
        raw = json.load(r)
    return {"updated_at": now_utc().isoformat(timespec="seconds"), "source": url.split("?")[0],
            "demo": False, "vessels": normalize(raw)}


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("ais")
    s.add_argument("--minutes", type=float, default=5)
    s.add_argument("--pattern", default=DEFAULT_PATTERN,
                   help=r'regex on the vessel name, e.g. "^(CMA CGM|APL|ANL|CNC) " for the whole group')
    sub.add_parser("demo")
    sub.add_parser("fetch")
    args = ap.parse_args()
    if args.cmd == "ais":
        write(cmd_ais(args.minutes, args.pattern))
    else:
        write(cmd_demo() if args.cmd == "demo" else cmd_fetch())
    return 0


if __name__ == "__main__":
    sys.exit(main())
