#!/usr/bin/env python3
"""CMA CGM fleet positions for the map (standard library only).

Commands:
  ais [--minutes N] [--pattern REGEX]
           Listen to the aisstream.io global AIS feed for N minutes (default: 5),
           keep ships whose name matches the pattern (default: "^CMA CGM ")
           and update data/vessels.json + data/vessels.js.
           Key: AISSTREAM_API_KEY environment variable.
           Known positions are kept for 48 h if the ship is not heard again.
  demo     Write SIMULATED positions.
  fetch    Query another HTTP API (VESSELS_API_URL, VESSELS_API_KEY, VESSELS_API_AUTH);
           adapt normalize() to the response format.

The front end reloads data/vessels.js every 5 minutes: schedule `vessels.py ais`
(Windows Task Scheduler, e.g. every 30 min) to keep the map up to date.

aisstream limitation: it relies on shore-based receivers. Ships out at sea
(out of range of the coast) are not received; their last position stays on the map for 48 h.
"""
